    /**
     * Какие поля в строках переводятся.
     *
     * Перевод лежит в той же строке под суффиксом языка: `city` — значение по
     * умолчанию, `city_kk` — казахская версия. Хранить две отдельные таблицы
     * пришлось бы дублировать и цифры (тарифы, годы, площади), а они на всех
     * языках одни и те же и разъезжались бы при первой же правке.
     */
    public const TRANSLATABLE_ROWS = [
        'site_branches' => ['city', 'role', 'address'],
        'site_delivery' => ['city'],
        'site_faq' => ['q', 'a'],
        'site_stats' => ['value', 'label'],
        'site_production' => ['title', 'text'],
        'site_advantages' => ['title', 'text'],
        'site_projects' => ['title', 'city', 'products'],
    ];

    /** Обычные строки-настройки, у которых есть языковые версии. */
    public const TRANSLATABLE_VALUES = ['site_hours'];

    /** Настройка либо значение по умолчанию из реестра. */
    private static function value(string $key): mixed
    {
        $value = Setting::get($key, self::DEFAULTS[$key] ?? null);

        if (in_array($key, self::TRANSLATABLE_VALUES, true)) {
            $localized = Setting::get($key.'_'.app()->getLocale(), self::DEFAULTS[$key.'_'.app()->getLocale()] ?? null);

            return static::filled($localized) ? $localized : $value;
        }

        if (isset(self::TRANSLATABLE_ROWS[$key]) && is_array($value)) {
            return static::localizeRows($value, self::TRANSLATABLE_ROWS[$key]);
        }

        return $value;
    }

    /**
     * Подставляет языковые версии полей и убирает служебные суффиксы —
     * витрина получает обычную строку и про языки не знает.
     */
    public static function localizeRows(array $rows, array $fields, ?string $locale = null): array
    {
        $locale ??= app()->getLocale();

        return array_map(function (array $row) use ($fields, $locale) {
            foreach ($fields as $field) {
                $translated = $row[$field.'_'.$locale] ?? null;

                if (static::filled($translated)) {
                    $row[$field] = $translated;
                }
            }

            // Суффиксы наружу не отдаём: иначе они всплыли бы в вёрстке
            // и в составе заказа.
            foreach (array_keys($row) as $key) {
                foreach (Locales::ALL as $suffix) {
                    if (str_ends_with((string) $key, '_'.$suffix)) {
                        unset($row[$key]);
                    }
                }
            }

            return $row;
        }, array_values($rows));
    }

    private static function filled(mixed $value): bool
    {
        return $value !== null && trim((string) $value) !== '';
    }

