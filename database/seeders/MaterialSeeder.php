<?php

namespace Database\Seeders;

use App\Models\Company;
use App\Models\Material;
use Illuminate\Database\Seeder;

/**
 * Стартовая номенклатура склада QAZAQ TAS: сырьё и расходники для
 * мраморного композита (МАФ и тротуарная плитка). Остатки нулевые —
 * приход оформляет бухгалтер/админ на странице «Склад» с ценой закупки,
 * по ней же считается материальный расход сделки.
 */
class MaterialSeeder extends Seeder
{
    public function run(): void
    {
        $companyId = Company::orderBy('id')->value('id');

        $materials = [
            ['Мраморная крошка, фракция 0–2 мм', 'тонна'],
            ['Мраморная крошка, фракция 2–5 мм', 'тонна'],
            ['Мраморная мука (микрокальцит)', 'тонна'],
            ['Цемент белый М500', 'мешок'],
            ['Цемент серый М400', 'мешок'],
            ['Полиэфирная смола', 'кг'],
            ['Отвердитель', 'кг'],
            ['Гелькоут', 'кг'],
            ['Пигмент (краситель)', 'кг'],
            ['Пластификатор', 'литр'],
            ['Гидрофобизатор / пропитка', 'литр'],
            ['Разделительная смазка для форм', 'литр'],
            ['Фиброволокно', 'кг'],
            ['Арматура / закладные', 'кг'],
            ['Форма (матрица) полиуретановая', 'штук'],
            ['Шлифовальный круг / расходники', 'штук'],
            ['Стрейч-плёнка', 'рулон'],
            ['Паллета деревянная', 'штук'],
        ];

        foreach ($materials as [$name, $unit]) {
            Material::firstOrCreate(
                ['company_id' => $companyId, 'name' => $name],
                ['unit' => $unit, 'quantity' => 0, 'price' => 0]
            );
        }
    }
}
